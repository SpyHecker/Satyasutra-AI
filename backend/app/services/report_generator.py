"""
Report Generator — produces evidence-cited case reports.

Aggregates knowledge graph data, timeline events, and detected
contradictions into a structured Markdown investigation report
with inline evidence-ID citations.
"""

import logging
from datetime import datetime, timezone

logger = logging.getLogger(__name__)


def generate_report(case_data: dict) -> dict:
    """
    Generate a draft investigation report with inline evidence citations.

    Parameters
    ----------
    case_data : dict
        Aggregated case data including:
        - evidence: list of evidence metadata
        - graph: serialized knowledge graph
        - timeline: chronological events
        - timeline_gaps: detected temporal gaps
        - contradictions: detected conflicts

    Returns
    -------
    dict
        Report dict with:
        - title (str)
        - generated_at (str): ISO timestamp
        - markdown (str): full report in Markdown
        - sections (list[dict]): structured sections
        - stats (dict): report statistics
    """
    evidence_list = case_data.get("evidence", [])
    graph_data = case_data.get("graph", {})
    timeline = case_data.get("timeline", [])
    timeline_gaps = case_data.get("timeline_gaps", [])
    contradictions = case_data.get("contradictions", [])

    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    sections = []
    md_parts = []

    # ---- Header ----
    md_parts.append("# 📋 SatyaSutra Investigation Report")
    md_parts.append("")
    md_parts.append(f"**Generated:** {now}")
    md_parts.append(f"**Status:** Investigator-Review Draft")
    md_parts.append(f"**Evidence Items:** {len(evidence_list)}")
    md_parts.append("")
    md_parts.append("> ⚠️ **DISCLAIMER:** This is an AI-generated investigator-review draft. "
                    "It is NOT a court-ready document. All findings require human verification "
                    "and should be treated as preliminary analysis only.")
    md_parts.append("")
    md_parts.append("---")
    md_parts.append("")

    # ---- Section 1: Executive Summary ----
    summary_section = _generate_summary(evidence_list, graph_data, timeline, contradictions)
    sections.append({"title": "Executive Summary", "content": summary_section})
    md_parts.append(summary_section)

    # ---- Section 2: Evidence Inventory ----
    evidence_section = _generate_evidence_inventory(evidence_list)
    sections.append({"title": "Evidence Inventory", "content": evidence_section})
    md_parts.append(evidence_section)

    # ---- Section 3: Entity Analysis ----
    entity_section = _generate_entity_analysis(graph_data, evidence_list)
    sections.append({"title": "Entity Analysis", "content": entity_section})
    md_parts.append(entity_section)

    # ---- Section 4: Timeline Reconstruction ----
    timeline_section = _generate_timeline_section(timeline, timeline_gaps)
    sections.append({"title": "Timeline Reconstruction", "content": timeline_section})
    md_parts.append(timeline_section)

    # ---- Section 5: Contradictions & Discrepancies ----
    contradiction_section = _generate_contradiction_section(contradictions)
    sections.append({"title": "Contradictions & Discrepancies", "content": contradiction_section})
    md_parts.append(contradiction_section)

    # ---- Section 6: Knowledge Graph Summary ----
    graph_section = _generate_graph_section(graph_data)
    sections.append({"title": "Knowledge Graph Summary", "content": graph_section})
    md_parts.append(graph_section)

    # ---- Section 7: Recommendations ----
    recommendations_section = _generate_recommendations(contradictions, timeline_gaps, graph_data)
    sections.append({"title": "Recommendations", "content": recommendations_section})
    md_parts.append(recommendations_section)

    # ---- Footer ----
    md_parts.append("---")
    md_parts.append("")
    md_parts.append(f"*Report generated by SatyaSutra AI on {now}. "
                    "This is an automated draft for investigator review.*")

    full_markdown = "\n".join(md_parts)

    return {
        "title": "SatyaSutra Investigation Report",
        "generated_at": now,
        "markdown": full_markdown,
        "sections": sections,
        "stats": {
            "evidence_count": len(evidence_list),
            "entity_count": graph_data.get("stats", {}).get("total_nodes", 0),
            "edge_count": graph_data.get("stats", {}).get("total_edges", 0),
            "timeline_events": len(timeline),
            "timeline_gaps": len(timeline_gaps),
            "contradictions": len(contradictions),
        },
    }


def _generate_summary(evidence_list, graph_data, timeline, contradictions):
    """Generate executive summary section."""
    lines = []
    lines.append("## 1. Executive Summary")
    lines.append("")

    stats = graph_data.get("stats", {})
    categories = stats.get("categories", {})

    lines.append(f"This report analyzes **{len(evidence_list)} evidence item(s)** "
                 f"uploaded to the case. The NLP pipeline extracted "
                 f"**{stats.get('total_nodes', 0)} unique entities** across "
                 f"**{len(categories)} categories**, resulting in "
                 f"**{stats.get('total_edges', 0)} relationship links**.")
    lines.append("")

    if timeline:
        lines.append(f"The timeline reconstruction identified **{len(timeline)} "
                     f"temporal events** across the evidence corpus.")
        lines.append("")

    if contradictions:
        high = sum(1 for c in contradictions if c.get("severity") == "high")
        med = sum(1 for c in contradictions if c.get("severity") == "medium")
        lines.append(f"⚡ **{len(contradictions)} contradiction(s)** were detected "
                     f"across evidence sources ({high} high severity, {med} medium).")
        lines.append("")

    if not evidence_list:
        lines.append("*No evidence has been uploaded yet. Upload evidence files to begin analysis.*")
        lines.append("")

    lines.append("")
    return "\n".join(lines)


def _generate_evidence_inventory(evidence_list):
    """Generate evidence inventory section."""
    lines = []
    lines.append("## 2. Evidence Inventory")
    lines.append("")

    if not evidence_list:
        lines.append("*No evidence uploaded.*")
        lines.append("")
        return "\n".join(lines)

    lines.append("| # | Filename | Type | Status | Entities | Evidence ID |")
    lines.append("|---|----------|------|--------|----------|-------------|")

    for idx, ev in enumerate(evidence_list, 1):
        ev_data = ev if isinstance(ev, dict) else (ev.model_dump() if hasattr(ev, "model_dump") else {})
        filename = ev_data.get("filename", "unknown")
        ftype = ev_data.get("file_type", "?")
        status = ev_data.get("status", "unknown")
        entity_count = ev_data.get("entity_count", len(ev_data.get("entities", [])))
        eid = ev_data.get("id", "?")

        status_icon = "✅" if status == "processed" else "⚠️"
        lines.append(f"| {idx} | {filename} | {ftype.upper()} | {status_icon} {status} | {entity_count} | `[{eid}]` |")

    lines.append("")
    lines.append("")
    return "\n".join(lines)


def _generate_entity_analysis(graph_data, evidence_list):
    """Generate entity analysis section."""
    lines = []
    lines.append("## 3. Entity Analysis")
    lines.append("")

    stats = graph_data.get("stats", {})
    categories = stats.get("categories", {})
    nodes = graph_data.get("nodes", [])

    if not nodes:
        lines.append("*No entities extracted. Upload and process evidence to see analysis.*")
        lines.append("")
        return "\n".join(lines)

    # Category breakdown
    lines.append("### Entity Categories")
    lines.append("")
    lines.append("| Category | Count |")
    lines.append("|----------|-------|")
    for cat, count in sorted(categories.items(), key=lambda x: -x[1]):
        lines.append(f"| {cat} | {count} |")
    lines.append("")

    # Key entities by category
    for cat in ["Person", "Location", "Organization", "Object", "Time"]:
        cat_nodes = [n for n in nodes if n.get("category") == cat]
        if cat_nodes:
            lines.append(f"### {cat}s Identified")
            lines.append("")
            # Sort by mention count
            cat_nodes.sort(key=lambda n: -n.get("mention_count", 1))
            for n in cat_nodes[:10]:  # Top 10
                sources = n.get("sources", [])
                source_citations = ", ".join(f"`[{s}]`" for s in sources) if sources else "—"
                lines.append(f"- **{n.get('label', '?')}** — "
                             f"mentioned {n.get('mention_count', 1)}× "
                             f"(Sources: {source_citations})")
            lines.append("")

    lines.append("")
    return "\n".join(lines)


def _generate_timeline_section(timeline, timeline_gaps):
    """Generate timeline reconstruction section."""
    lines = []
    lines.append("## 4. Timeline Reconstruction")
    lines.append("")

    if not timeline:
        lines.append("*No temporal events extracted. Upload evidence with date/time references.*")
        lines.append("")
        return "\n".join(lines)

    lines.append("### Chronological Events")
    lines.append("")

    for idx, evt in enumerate(timeline, 1):
        timestamp = evt.get("timestamp", "?")
        description = evt.get("description", "")[:150]
        source = evt.get("source_name", "unknown")
        source_id = evt.get("source_id", "?")
        is_approx = evt.get("is_approximate", False)

        approx_marker = " *(approx.)*" if is_approx else ""
        lines.append(f"{idx}. **{timestamp}**{approx_marker} — {description} "
                     f"`[{source_id}]`")

    lines.append("")

    # Gaps
    if timeline_gaps:
        lines.append("### ⚠️ Temporal Gaps Detected")
        lines.append("")
        for gap in timeline_gaps:
            lines.append(f"- **{gap.get('duration_hours', '?')} hours** — "
                         f"from {gap.get('start', '?')} to {gap.get('end', '?')}")
            lines.append(f"  {gap.get('description', '')}")
        lines.append("")

    lines.append("")
    return "\n".join(lines)


def _generate_contradiction_section(contradictions):
    """Generate contradictions section."""
    lines = []
    lines.append("## 5. Contradictions & Discrepancies")
    lines.append("")

    if not contradictions:
        lines.append("*No contradictions detected across evidence sources.*")
        lines.append("")
        return "\n".join(lines)

    lines.append(f"**{len(contradictions)} contradiction(s) detected:**")
    lines.append("")

    for idx, c in enumerate(contradictions, 1):
        severity = c.get("severity", "medium")
        severity_icon = "🔴" if severity == "high" else "🟡" if severity == "medium" else "🟢"
        confidence = c.get("confidence", 0)

        lines.append(f"### {severity_icon} Contradiction #{idx}: {c.get('type', 'unknown').replace('_', ' ').title()}")
        lines.append("")
        lines.append(f"**Severity:** {severity.title()} | **Confidence:** {confidence:.0%}")
        lines.append("")
        lines.append(f"**Source A** (`[{c.get('source_a', '?')}]` — {c.get('source_a_name', '?')}):")
        lines.append(f"> {c.get('statement_a', 'N/A')}")
        lines.append("")
        lines.append(f"**Source B** (`[{c.get('source_b', '?')}]` — {c.get('source_b_name', '?')}):")
        lines.append(f"> {c.get('statement_b', 'N/A')}")
        lines.append("")
        lines.append(f"**Explanation:** {c.get('explanation', 'N/A')}")
        lines.append("")
        lines.append("---")
        lines.append("")

    return "\n".join(lines)


def _generate_graph_section(graph_data):
    """Generate knowledge graph summary section."""
    lines = []
    lines.append("## 6. Knowledge Graph Summary")
    lines.append("")

    stats = graph_data.get("stats", {})
    nodes = graph_data.get("nodes", [])
    links = graph_data.get("links", [])

    if not nodes:
        lines.append("*Knowledge graph is empty. Upload evidence to build the graph.*")
        lines.append("")
        return "\n".join(lines)

    lines.append(f"The case knowledge graph contains **{stats.get('total_nodes', 0)} nodes** "
                 f"and **{stats.get('total_edges', 0)} edges**.")
    lines.append("")

    # Most connected nodes
    if nodes:
        lines.append("### Most Connected Entities")
        lines.append("")

        # Calculate degree from links
        degree = {}
        for link in links:
            src = link.get("source", "")
            tgt = link.get("target", "")
            degree[src] = degree.get(src, 0) + 1
            degree[tgt] = degree.get(tgt, 0) + 1

        # Enrich nodes with degree
        for node in nodes:
            node["_degree"] = degree.get(node["id"], 0)

        top_nodes = sorted(nodes, key=lambda n: -n["_degree"])[:8]

        lines.append("| Entity | Category | Connections | Mentions |")
        lines.append("|--------|----------|-------------|----------|")
        for n in top_nodes:
            lines.append(f"| {n.get('label', '?')} | {n.get('category', '?')} "
                         f"| {n['_degree']} | {n.get('mention_count', 1)} |")
        lines.append("")

    lines.append("")
    return "\n".join(lines)


def _generate_recommendations(contradictions, timeline_gaps, graph_data):
    """Generate recommendations section based on analysis."""
    lines = []
    lines.append("## 7. Recommendations for Further Investigation")
    lines.append("")

    recommendations = []

    # Based on contradictions
    for c in contradictions:
        if c.get("severity") == "high":
            recommendations.append(
                f"🔍 **Resolve contradiction:** {c.get('type', '').replace('_', ' ').title()} "
                f"— verify claims from `[{c.get('source_a', '?')}]` against "
                f"`[{c.get('source_b', '?')}]`."
            )

    # Based on timeline gaps
    for gap in timeline_gaps:
        recommendations.append(
            f"📅 **Fill temporal gap:** {gap.get('duration_hours', '?')} hours unaccounted "
            f"between {gap.get('start', '?')} and {gap.get('end', '?')}. "
            f"Seek additional evidence covering this period."
        )

    # Based on graph analysis
    nodes = graph_data.get("nodes", [])
    person_nodes = [n for n in nodes if n.get("category") == "Person"]
    if person_nodes:
        single_source = [n for n in person_nodes
                         if len(n.get("sources", [])) == 1]
        if single_source:
            recommendations.append(
                f"👤 **Cross-reference persons:** {len(single_source)} person(s) appear "
                f"in only one evidence source. Seek corroborating evidence."
            )

    if not recommendations:
        lines.append("*No specific recommendations at this time. Continue evidence collection.*")
    else:
        for rec in recommendations:
            lines.append(f"- {rec}")

    lines.append("")
    lines.append("")
    return "\n".join(lines)
